"""Optional educational image processing. Canonical data: data/species.source.json.

No scientific records or population estimates live in this script.
Private previews go to .generated/images. Public JSON is generated by build-data.mjs.
Requires Pillow; npm run build does not require Python or Pillow.
"""
from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path


def pixelate_image(image_path: Path, output_path: Path, detail: int = 64,
                   width: int = 800, height: int = 600) -> None:
    """Educational preview; detail is unrelated to animal counts."""
    from PIL import Image, ImageOps

    if not 8 <= detail <= 200 or width <= 0 or height <= 0:
        raise ValueError("detail must be 8..200; width/height must be positive")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(image_path) as source:
        fitted = ImageOps.fit(ImageOps.exif_transpose(source).convert("RGB"), (width, height))
        rows = max(1, round(detail * height / width))
        small = fitted.resize((detail, rows), Image.Resampling.BILINEAR)
        small.resize((width, height), Image.Resampling.NEAREST).save(output_path)


def generate_previews(project_root: Path, detail: int = 64) -> list[Path]:
    """Read validated canonical data; only licence-confirmed photos are processed."""
    root = project_root.resolve()
    subprocess.run(["node", str(root / "scripts/build-data.mjs"), "--validate-only"],
                   check=True, cwd=root)
    document = json.loads((root / "data/species.source.json").read_text(encoding="utf-8"))
    outputs = []
    for species in document["catalog"]:
        for index, image in enumerate(species["images"]):
            if not image["licenseVerified"]:
                continue
            source = (root / image["path"]).resolve()
            if not source.is_relative_to(root):
                raise ValueError(f"Image outside project: {image['path']}")
            output = root / ".generated/images" / f"{species['id']}-{index + 1}.png"
            pixelate_image(source, output, detail)
            outputs.append(output)
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--detail", type=int, default=64)
    args = parser.parse_args()
    try:
        if not 8 <= args.detail <= 200:
            raise ValueError("detail must be 8..200")
        files = generate_previews(Path(__file__).resolve().parent.parent, args.detail)
        print(f"Created {len(files)} licensed educational previews. Public JSON unchanged.")
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Image processing failed: {error}\n")
