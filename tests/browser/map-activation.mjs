// Optional browser regression suite. Uses an externally provided Playwright runtime;
// the application acquires no browser automation dependency.
import assert from 'node:assert/strict'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.MAP_BASE_URL || 'http://127.0.0.1:5174'
const output = '.generated/map-activation'
await mkdir(output,{recursive:true})
const species=JSON.parse(await readFile('public/data/species.json'))
const regions=['batken','osh','jalal-abad','naryn','issyk-kul','chuy','talas']
const count=id=>id==='jalal-abad'?5:id==='issyk-kul'?1:0
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})})
const errors=[],checks=[]
const check=(name)=>checks.push(name)
const context=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'})
await context.addInitScript(()=>localStorage.setItem('redbook.locale.v1','ru'))
const page=await context.newPage()
page.on('pageerror',error=>errors.push(error.message))
const media=new Set(),external=new Set()
page.on('request',r=>{if(r.url().includes('.webp'))media.add(r.url());if(!r.url().startsWith(base)&&!r.url().startsWith('data:'))external.add(r.url())})
const waitCount=async(n,p=page)=>p.waitForFunction(n=>document.querySelectorAll('.regional-species').length===n,n)
try{
 await page.goto(base+'/map');await waitCount(6)
 check('full map opens with all six documented links')
 for(const[id,index]of regions.map((id,i)=>[id,i])){
  await page.locator('.region-choices button').nth(index).click()
  assert.equal(await page.locator(`path[data-region="${id}"]`).getAttribute('aria-pressed'),'true')
  assert.equal(new URL(page.url()).searchParams.get('region'),id)
  await waitCount(count(id))
  if(!count(id))assert.match(await page.locator('.map-empty').textContent(),/Подтверждённые региональные сведения пока отсутствуют/)
 }
 check('click selection, highlight, URL and empty states for all seven oblasts')
 await page.locator('.map-reset').click();await waitCount(6)
 assert.equal(new URL(page.url()).search,'')
 const target=species.find(s=>s.id==='kaufmanns-tulip')
 for(const name of [...Object.values(target.names),target.scientificName]){
  await page.locator('#map-species-search').fill(name);await waitCount(1)
  assert.equal(await page.locator('.map-species-page').getAttribute('href'),'/species/kaufmanns-tulip')
 }
 check('search in KY UZ RU EN and Latin')
 await page.locator('.map-reset').click();await waitCount(6)
 const groups=page.locator('#map-region-panel .group-filter button')
 for(let i=0;i<await groups.count();i++){
  const label=(await groups.nth(i).textContent()).trim();await groups.nth(i).click()
  await waitCount(['Все группы','Растения'].includes(label)?6:0)
 }
 check('all organism group controls filter documented links only')
 await page.locator('.map-reset').click();await waitCount(6)
 for(const id of regions){
  const path=page.locator(`path[data-region="${id}"]`);await path.focus();await path.press('Enter')
  assert.equal(await path.getAttribute('aria-pressed'),'true');await waitCount(count(id))
 }
 await page.locator('path[data-region="talas"]').press('Space');await waitCount(6)
 check('keyboard Enter and Space selection for seven oblasts')
 await page.locator('#map-species-search').fill('Tianschaniella');await waitCount(1)
 assert.match(await page.locator('.map-observation').textContent(),/2000-07-20/)
 assert.match(await page.locator('.regional-species').textContent(),/дата публикации неизвестна/)
 await page.locator('.map-species-page').click();await page.waitForURL('**/species/tianschaniella-umbellifera')
 assert.match(await page.locator('main').textContent(),/Tianschaniella umbellulifera/)
 await page.goBack();await page.locator('#map-species-search').waitFor();await waitCount(1)
 await page.locator('.map-reset').click();await waitCount(6)
 check('historical date, unknown publication date, species page and browser Back')
 await page.screenshot({path:output+'/after-desktop.png',fullPage:false})
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
 await mobile.addInitScript(()=>localStorage.setItem('redbook.locale.v1','ru'))
 const phone=await mobile.newPage();phone.on('pageerror',error=>errors.push(error.message))
 await phone.goto(base+'/map?region=issyk-kul');await waitCount(1,phone)
 assert.equal(await phone.locator('body').evaluate(el=>el.scrollWidth<=innerWidth),true)
 await phone.locator('.region-choices button').nth(0).tap();await waitCount(0,phone)
 assert.match(await phone.locator('.map-empty').textContent(),/Подтверждённые региональные сведения пока отсутствуют/)
 await phone.locator('.map-reset').tap();await waitCount(6,phone)
 await phone.locator('#map-species-search').fill('Malus sieversii');await waitCount(1,phone)
 await phone.screenshot({path:output+'/after-mobile.png',fullPage:false})
 check('390px touch selection, search, reset and no horizontal overflow')
 await phone.goto(base+'/');await phone.locator('.map-preview .oblast-map').waitFor()
 await phone.locator('.map-preview').scrollIntoViewIfNeeded()
 const path=phone.locator('path[data-region="issyk-kul"]');await path.scrollIntoViewIfNeeded()
 const point=await path.evaluate(el=>{const box=el.getBBox(),svg=el.ownerSVGElement;for(let x=box.x;x<box.x+box.width;x+=4)for(let y=box.y;y<box.y+box.height;y+=4){const p=svg.createSVGPoint();p.x=x;p.y=y;if(!el.isPointInFill(p))continue;const q=p.matrixTransform(el.getScreenCTM());if(q.y>0&&q.y<innerHeight&&document.elementFromPoint(q.x,q.y)===el)return{x:q.x,y:q.y}}throw Error('No visible touch point')})
 await phone.touchscreen.tap(point.x,point.y)
 await phone.locator('.map-overview-action').tap();await phone.waitForURL('**/map?region=issyk-kul');await waitCount(1,phone)
 check('mobile SVG touch preview → full map preserves the selected oblast')
 assert.equal(await phone.locator('path[data-region="issyk-kul"]').getAttribute('aria-pressed'),'true')
 await phone.goto(base+'/');await phone.locator('.map-preview .oblast-map').waitFor()
 await phone.locator('.map-preview').scrollIntoViewIfNeeded()
 await phone.locator('path[data-region="issyk-kul"]').focus()
 await phone.locator('path[data-region="issyk-kul"]').press('Enter')
 await phone.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}))
 await phone.locator('.main-navigation a[href="/map"]').focus()
 await phone.locator('.main-navigation a[href="/map"]').tap();await phone.waitForURL(base+'/map');await waitCount(6,phone)
 assert.equal(await phone.locator('path[aria-pressed="true"]').count(),0)
 check('map navigation clears preview selection when the URL has no region')
 await mobile.close()
 const failurePage=await context.newPage()
 await failurePage.route('**/data/species.json',route=>route.fulfill({status:503,body:'unavailable'}))
 await failurePage.goto(base+'/map')
 await failurePage.locator('#map [role="alert"]').waitFor()
 assert.equal(await failurePage.locator('.regional-species').count(),0)
 await failurePage.close()
 check('catalog load failure is visible and never masked by regional loading')
 assert.deepEqual(errors,[]);assert.deepEqual([...external],[])
 assert.ok(media.size<20,`map should not preload 161 photos: ${media.size}`)
 check('local-only resources, limited lazy images and no browser exceptions')
 await writeFile(output+'/browser-results.json',JSON.stringify({checks,errors,external:[...external],desktopImagesRequested:media.size},null,2)+'\n')
 console.log(JSON.stringify({passed:checks.length,checks,imagesRequested:media.size},null,2))
}finally{await browser.close()}
